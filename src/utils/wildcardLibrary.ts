/**
 * Returns 6 distinct prompts for a Wildcard round.
 * Prioritizes prompts that haven't been revealed yet in this session.
 * If fewer than 6 unused prompts remain, fills remaining slots from previously revealed
 * without duplicates within the 6 selected cards.
 * Returns { cards: WildcardPrompt[], isDeckExhausted: boolean }
 */
export function drawSixWildcards(usedIds: Set<string>): {
  cards: WildcardPrompt[];
  isDeckExhausted: boolean;
  unrevealedCount: number;
} {
  const unused = WILDCARD_LIBRARY.filter(p => !usedIds.has(p.id));
  const isDeckExhausted = unused.length === 0;

  // Shuffle array utility
  const shuffle = <T>(arr: T[]): T[] => {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  };

  const shuffledUnused = shuffle(unused);

  if (shuffledUnused.length >= 6) {
    return {
      cards: shuffledUnused.slice(0, 6),
      isDeckExhausted: false,
      unrevealedCount: unused.length
    };
  }

  // Fewer than 6 unused remain: take all available unused, then backfill from used without duplicating
  const chosen = [...shuffledUnused];
  const chosenIds = new Set(chosen.map(c => c.id));

  const eligibleUsed = shuffle(WILDCARD_LIBRARY.filter(p => !chosenIds.has(p.id)));
  for (const item of eligibleUsed) {
    if (chosen.length >= 6) break;
    chosen.push(item);
    chosenIds.add(item.id);
  }

  return {
    cards: shuffle(chosen),
    isDeckExhausted: isDeckExhausted,
    unrevealedCount: unused.length
  };
}
